/**
 * The house as a frame's cards see it when Home Assistant speaks these words: its formatter says an attribute's
 * value in the page's language where `words` has it, else the value as it is, as Home Assistant does.
 */
export const speakingAttributes =
  (words: Words) =>
  (hass: HomeAssistant): HomeAssistant => ({
    ...hass,
    formatEntityAttributeValue: (stateObj: HassEntity, attribute: string, value?: unknown) => {
      const raw = String(value ?? stateObj.attributes[attribute] ?? '');
      return words[hass.language]?.[`${attribute}.${raw}`] ?? raw;
    },
  });
