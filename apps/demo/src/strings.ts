/** A word of the demo in `language`. */
export const t = (
  language: LanguageCode,
  key: StringKey,
  values?: Record<string, string | number>,
): string => {
  const template = TABLES[language][key];
  return values
    ? template.replace(/\{(\w+)\}/g, (match, name: string) =>
        name in values ? String(values[name]) : match,
      )
    : template;
};
